#Arithmetic Operators
a = 10
b = 5

print("Addition:", a + b)        # Addition
print("Subtraction:", a - b)     # Subtraction
print("Multiplication:", a * b)  # Multiplication
print("Division:", a / b)        # Division
print("Modulus:", a % b)         # Modulus
print("Exponentiation:", a ** b)  # Exponentiation    


#Relational Operators
x = 10
y = 5

print("Equal to:", x == y)        # Equal to
print("Not equal to:", x != y)    # Not equal to
print("Greater than:", x > y)     # Greater than
print("Less than:", x < y)        # Less than
print("Greater than or equal to:", x >= y)  # Greater than or equal to
print("Less than or equal to:", x <= y)     # Less than or equal to

#assignment Operators
a = 10
b = 5
a += b  # a = a + b
print("Addition assignment:", a)  # Addition assignment

a -= b  # a = a - b
print("Subtraction assignment:", a)  # Subtraction assignment

a *= b  # a = a * b
print("Multiplication assignment:", a)  # Multiplication assignment

a /= b  # a = a / b
print("Division assignment:", a)  # Division assignment     

a **= b  # a = a ** b
print("Exponentiation assignment:", a)  # Exponentiation assignment


#logical Operators
p = True
q = False

print("Logical AND:", p and q)  # Logical AND
print("Logical OR:", p or q)    # Logical OR
print("Logical NOT:", not p)     # Logical NOT